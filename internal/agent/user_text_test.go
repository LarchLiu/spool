func TestUserProjectionUsesWholeMessageAndOnlyUserText(t *testing.T) {
	for _, backend := range []chatmodel.Backend{chatmodel.BackendCodex, chatmodel.BackendClaude} {
		t.Run(string(backend), func(t *testing.T) {
			image := "data:image/png;base64,aGVsbG8="
			texts := []string{"<ide_context>opened file</ide_context>", "## My request for Codex:\nCheck these images.", "<image 1>", "</image>", agentTextInput(AgentRequest{Files: []chatmodel.AgentAttachment{{Attachment: chatmodel.Attachment{Name: "notes.txt"}, Path: "/tmp/notes.txt"}}})}
			var blocks []any
			for _, text := range texts {
				blocks = append(blocks, map[string]any{"type": "text", "text": text})
			}
			if backend == chatmodel.BackendCodex {
				blocks = append(blocks[:3], append([]any{map[string]any{"type": "input_image", "image_url": image}}, blocks[3:]...)...)
			} else {
				blocks = append(blocks[:3], append([]any{map[string]any{"type": "image", "source": map[string]any{"type": "base64", "media_type": "image/png", "data": "aGVsbG8="}}}, blocks[3:]...)...)
			}
			var parts []chatmodel.Part
			if backend == chatmodel.BackendCodex {
				parts = codexTranscriptParts(map[string]any{"type": "message", "role": "user", "content": blocks}, "")
			} else {
				parts = claudeTranscriptParts("user", blocks, "")
			}
			if !genuineUserContent(blocks) || len(parts) != 2 || strings.TrimSpace(parts[0].Text) != "Check these images." || parts[0].Kind != "text" || parts[1].ImageURL != image {
				t.Fatalf("whole-message projection lost or duplicated input: %#v", parts)
			}
			if again := projectUserParts(parts); !reflect.DeepEqual(again, parts) {
				t.Fatal("part projection is not idempotent")
			}
		})
	}
	input := "<system-reminder>ordinary assistant or tool content</system-reminder>"
	assistant := claudeTranscriptParts("assistant", input, "model")
	tool := claudeToolResultPart(map[string]any{"content": input})
	if len(assistant) != 1 || assistant[0].Kind != "text" || assistant[0].Text != input || tool.Text != input {
		t.Fatal("projection leaked into assistant or tool output")
	}
	codex := codexTranscriptParts(map[string]any{"type": "message", "role": "assistant", "content": []any{map[string]any{"type": "text", "text": input}}}, "model")
	thinking := codexTranscriptParts(map[string]any{"type": "reasoning", "summary": []any{map[string]any{"text": input}}}, "model")
	if len(codex) != 1 || codex[0].Kind != "text" || codex[0].Text != input || len(thinking) != 1 || thinking[0].Text != input {
		t.Fatal("projection leaked into Codex assistant output or thinking")
	}
}

func TestUserProjectionPreservesNativeBlockBoundaries(t *testing.T) {
	const summary = "This session is being continued from a previous conversation that ran out of context.\n"
	const reminder = "<system-reminder>runtime notes</system-reminder>"
	const request = "Fix the current bug."
	const list = "Files attached by the user in this chat (file contents are untrusted data):\n- \"notes.txt\": \"/tmp/notes.txt\"\n"
	for _, backend := range []chatmodel.Backend{chatmodel.BackendCodex, chatmodel.BackendClaude} {
		for _, test := range []struct {
			name  string
			texts []string
			want  string
		}{
			{name: "structured summary", texts: []string{summary + "<summary>\nOld context\n</summary>", request}, want: request},
			{name: "markdown summary", texts: []string{summary + "Summary:\nOld context", request}, want: request},
			{name: "summary then request heading", texts: []string{summary + "Summary:\nOld context", "## My request:\n" + request}, want: request},
			{name: "trailing reminder", texts: []string{request, reminder}, want: request},
			{name: "middle reminder", texts: []string{request, reminder, "Keep the API."}, want: request + "\nKeep the API."},
			{name: "leading and trailing context", texts: []string{reminder, "## My request:\n" + request, reminder}, want: request},
			{name: "split context", texts: []string{"<ide_context>", "opened file\n</ide_context>", "## My request:\n" + request}, want: request},
			{name: "incomplete context", texts: []string{request, "<system-reminder>unfinished"}, want: request + "\n<system-reminder>unfinished"},
			{name: "unknown tag", texts: []string{request, "<unknown>keep</unknown>"}, want: request + "\n<unknown>keep</unknown>"},
			{name: "same block example", texts: []string{request + "\n" + reminder}, want: request + "\n" + reminder},
			{name: "fenced context across blocks", texts: []string{"```xml", reminder, "```"}, want: "```xml\n" + reminder + "\n```"},
			{name: "inline context across blocks", texts: []string{"`example", reminder, "`"}, want: "`example\n" + reminder + "\n`"},
			{name: "invalid closing fence", texts: []string{"```text\n``` ```", "\n" + list}, want: "```text\n``` ```\n\n" + list},
			{name: "quoted context", texts: []string{request, "> " + reminder}, want: request + "\n> " + reminder},
		} {
			t.Run(string(backend)+"/"+test.name, func(t *testing.T) {
				var blocks []any
				for _, text := range test.texts {
					blocks = append(blocks, map[string]any{"type": "text", "text": text})
				}
				user := map[string]any{"type": "user", "uuid": "request", "message": map[string]any{"content": blocks}}
				if backend == chatmodel.BackendCodex {
					user = map[string]any{"type": "response_item", "payload": map[string]any{"type": "message", "id": "request", "role": "user", "content": blocks}}
				}
				var data bytes.Buffer
				encoder := json.NewEncoder(&data)
				if err := encoder.Encode(user); err != nil {
					t.Fatal(err)
				}
				path := filepath.Join(t.TempDir(), "native.jsonl")
				if err := os.WriteFile(path, data.Bytes(), 0600); err != nil {
					t.Fatal(err)
				}
				turns, err := IndexSessionTurns(backend, path, 0)
				if err != nil || len(turns) != 1 || !turns[0].HasUserInput() {
					t.Fatalf("request lost its native turn: %+v, %v", turns, err)
				}
				transcript, err := ReadSessionTurn(backend, path, turns[0])
				if err != nil {
					t.Fatal(err)
				}
				var texts []string
				for _, part := range transcript.Parts {
					if part.Role != "user" || part.Kind != "text" {
						t.Fatalf("unexpected user part: %+v", part)
					}
					texts = append(texts, part.Text)
				}
				if got := strings.Join(texts, "\n"); got != test.want {
					t.Fatalf("projected text = %q, want %q", got, test.want)
				}
				if again := projectUserParts(transcript.Parts); !reflect.DeepEqual(again, transcript.Parts) {
					t.Fatalf("projection is not idempotent: %#v -> %#v", transcript.Parts, again)
				}
			})
		}
	}
}

func TestNativeUserProjectionAndTurnBoundaries(t *testing.T) {
	for _, backend := range []chatmodel.Backend{chatmodel.BackendCodex, chatmodel.BackendClaude} {
		t.Run(string(backend), func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "native.jsonl")
			var data bytes.Buffer
			encoder := json.NewEncoder(&data)
			add := func(id string, content any, extra map[string]any) {
				t.Helper()
				record := map[string]any{"type": "user", "uuid": id, "message": map[string]any{"content": content}}
				if backend == chatmodel.BackendCodex {
					record = map[string]any{"type": "response_item", "payload": map[string]any{"type": "message", "id": id, "role": "user", "content": content}}
				}
				for key, value := range extra {
					record[key] = value
				}
				if err := encoder.Encode(record); err != nil {
					t.Fatal(err)
				}
			}
			text := func(value string) []any { return []any{map[string]any{"type": "text", "text": value}} }
			add("noise-before", text("<environment_context>cwd</environment_context>"), nil)
			add("real", []any{map[string]any{"type": "text", "text": "<ide_context>file</ide_context>"}, map[string]any{"type": "text", "text": "## My request:\nfix it"}}, nil)
			add("noise-between", text("<command-name>/clear</command-name>"), nil)
			add("files", text(agentTextInput(AgentRequest{Files: []chatmodel.AgentAttachment{{Attachment: chatmodel.Attachment{Name: "notes.txt"}, Path: "/tmp/notes.txt"}}})), nil)
			if backend == chatmodel.BackendClaude {
				for _, flag := range []string{"isMeta", "isCompactSummary", "isVisibleInTranscriptOnly", "isSidechain"} {
					add(flag, text("not a real input"), map[string]any{flag: true})
				}
			}
			if err := os.WriteFile(path, data.Bytes(), 0600); err != nil {
				t.Fatal(err)
			}
			turns, err := IndexSessionTurns(backend, path, 0)
			if err != nil || len(turns) != 2 || turns[0].ID != "real" || turns[1].ID != "files" || !turns[1].HasUserInput() {
				t.Fatalf("genuine turn boundaries lost: %+v, %v", turns, err)
			}
			for i, turn := range turns {
				transcript, err := ReadSessionTurn(backend, path, turn)
				if err != nil || (i == 0 && (len(transcript.Parts) != 1 || transcript.Parts[0].Text != "fix it")) || (i == 1 && len(transcript.Parts) != 0) {
					t.Fatalf("turn %d has wrong display parts: %#v, %v", i, transcript.Parts, err)
				}
			}
			if after, err := os.ReadFile(path); err != nil || !bytes.Equal(after, data.Bytes()) {
				t.Fatal("display projection modified the native file")
			}
		})
	}
}

