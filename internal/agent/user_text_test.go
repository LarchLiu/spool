func FuzzCleanUserTextIsIdempotent(f *testing.F) {
	for _, text := range []string{
		"", "plain text", "<environment_context>cwd</environment_context>\nrequest",
		"<ide_selection>\n```\n</ide_selection>\n```",
		"<image 1>\n</image>\nreference <image 1>",
		"question\n\n" + attachedFilesMarker + "\n- \"notes.txt\": \"/tmp/notes.txt\"\n",
	} {
		f.Add(text, false)
		f.Add(text, true)
	}
	f.Fuzz(func(t *testing.T, text string, images bool) {
		once := cleanUserText(text, images)
		twice := cleanUserText(once.Text, images)
		if twice.Text != once.Text {
			t.Fatalf("not idempotent: %q -> %q -> %q", text, once.Text, twice.Text)
		}
	})
}
