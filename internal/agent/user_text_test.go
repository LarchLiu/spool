	const prompt = "这个logo怎么样"
	const filename = "ChatGPT Image Oct 27, 2026, 12_00_03 AM.png"
	const imagePath = "/var/folders/kx/xrrjtzhd063412nw4qdtdfv40000gn/T/spool-attachments-1189180392/c0285dd24cc1ae50c215f5efe578b8b9/a83ce59c935828cc80b42eb36e83593c/" + filename
