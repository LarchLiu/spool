package com.cloudgeek.spool.android;

/** Generated from Web FileSource overrides and Pierre CSS Lab selection mixes. */
final class NativeSourcePalette {
    final int foreground;
    final int selection;
    final int gutterSelection;
    final int selectedNumber;
    NativeSourcePalette(boolean dark) {
        foreground = dark ? 0xfffafafa : 0xff0a0a0a;
        selection = dark ? 0xff503d34 : 0xfff7dfd6;
        gutterSelection = dark ? 0xff68483b : 0xfff3d2c7;
        selectedNumber = dark ? 0xff72b6ff : 0xff20649e;
    }
}
