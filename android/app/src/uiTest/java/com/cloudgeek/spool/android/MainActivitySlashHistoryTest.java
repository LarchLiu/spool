package com.cloudgeek.spool.android;

import static org.junit.Assert.*;

import android.graphics.Bitmap;
import android.graphics.Canvas;
import android.os.Build;
import android.view.View;
import java.io.File;
import java.io.FileOutputStream;
import java.nio.file.Files;
import java.util.HashSet;
import java.util.Set;
import org.json.JSONArray;
import org.json.JSONObject;
import org.junit.Assume;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.robolectric.annotation.Config;
import org.robolectric.annotation.GraphicsMode;
import org.robolectric.annotation.LooperMode;

/** Opt-in contract check against responses generated by TestSlashCommandHistoryBrowser. */
@RunWith(org.robolectric.RobolectricTestRunner.class)
@Config(sdk = {26, 35}, shadows = {MainActivityGoalTest.ShadowClient.class, MainActivityGoalTest.ShadowSeq.class})
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@LooperMode(LooperMode.Mode.PAUSED)
public class MainActivitySlashHistoryTest {
    @Test public void everyServerCommandAndReplyRendersBeforeTheContinuation() throws Exception {
        String directory = System.getenv("SPOOL_COMMAND_HISTORY_FIXTURES");
        Assume.assumeTrue("Generate synthetic server snapshots with TestSlashCommandHistoryBrowser first", directory != null);
        for (String backend : new String[] {"codex", "claude"}) try (MainActivityGoalTest.Harness h = new MainActivityGoalTest.Harness(true, true)) {
            JSONObject snapshot = new JSONObject(Files.readString(new File(directory, backend + ".json").toPath()));
            snapshot.put("id", "chat-one").put("project_id", "project-one").put("can_control", true);
            h.set("backend", backend); h.set("chat", snapshot); h.call("renderChat");
            NativeMarkwonHistory history = h.get("markwonHistory"); NativeMarkwonHistoryTest.await(history);
            Set<String> rendered = new HashSet<>();
            for (int position = 0; position < history.blocks(); position++) {
                history.scrollToPosition(position); NativeMarkwonHistoryTest.await(history);
                for (android.widget.TextView view : NativeMarkwonHistoryTest.texts(history)) rendered.add(view.getText().toString().trim());
            }
            JSONArray parts = snapshot.getJSONObject("transcript").getJSONArray("parts");
            assertEquals(backend.equals("claude") ? 18 : 14, parts.length());
            for (int i = 0; i < parts.length(); i++) assertTrue("Missing " + backend + " history text: " + parts.getJSONObject(i).getString("text"),
                    rendered.contains(parts.getJSONObject(i).getString("text")));
            assertTrue(rendered.contains("Continue checking history"));
            assertFalse(rendered.stream().anyMatch(text -> text.contains("<command-message>") || text.contains("Internal skill instructions")));
            history.scrollToPosition(0); NativeMarkwonHistoryTest.await(history);
            View root = h.get("root"); NativeMarkwonHistoryTest.layout(root);
            Bitmap image = Bitmap.createBitmap(root.getWidth(), root.getHeight(), Bitmap.Config.ARGB_8888);
            try (FileOutputStream output = new FileOutputStream(new File(directory, backend + "-android-api" + Build.VERSION.SDK_INT + ".png"))) {
                root.draw(new Canvas(image)); image.compress(Bitmap.CompressFormat.PNG, 100, output);
            } finally { image.recycle(); }
        }
    }
}
